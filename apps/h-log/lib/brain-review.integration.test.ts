import assert from "node:assert/strict";
import { createHash, randomUUID } from "node:crypto";
import test from "node:test";
import pg from "pg";
import { runBlogMigrations } from "../scripts/blog-migrations.mjs";
import { createBrainRepository } from "./brain-postgres-repository.ts";
import { parseBrainReviewQuery } from "./brain-review.ts";
import { handleBrainCaptureRequest } from "./brain-capture-http.ts";

const databaseUrl = process.env.DATABASE_URL;
const draft = { title: "재검토 합성 기록", originalText: "PRIVATE_REVIEW_ORIGINAL", publicTitle: "공개 합성 기록", publicSummary: "공개 사본 보존", publicBody: "공개 본문",
  kind: "question" as const, topic: "reliability" as const, basis: "question" as const, tags: [], questions: ["현재 조건은?"] };
const meta = (commandRevision: number) => ({ commandRevision, commandId: randomUUID() });
const query = (s = "") => parseBrainReviewQuery(new URLSearchParams(s));

test("version-bound review is atomic, idempotent, private and selected before cursor pagination", { skip: !databaseUrl && "DATABASE_URL is required" }, async () => {
  const adminUrl = new URL(databaseUrl!); adminUrl.pathname = "/postgres";
  const admin = new pg.Client({ connectionString: adminUrl.toString() }); await admin.connect();
  const name = "hlog_review_" + randomUUID().replaceAll("-", ""); await admin.query(`create database ${name}`);
  const url = new URL(databaseUrl!); url.pathname = "/" + name;
  const pool = new pg.Pool({ connectionString: url.toString() });
  try {
    await runBlogMigrations(url.toString());
    const repo = createBrainRepository(pool), save = meta(0);
    const first = await repo.saveDraft(draft, undefined, 0, save);
    const canonical = (value: unknown): unknown => Array.isArray(value) ? value.map(canonical) : value && typeof value === "object"
      ? Object.fromEntries(Object.entries(value).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0).map(([key, item]) => [key, canonical(item)])) : value;
    const legacyFingerprint = createHash("sha256").update(JSON.stringify(canonical({ action: "save", id: null, revision: 0, commandRevision: 0, draft }))).digest("hex");
    assert.equal((await pool.query("select request_fingerprint from admin_actions where command_id=$1", [save.commandId])).rows[0].request_fingerprint, legacyFingerprint);
    const node = async () => (await repo.getOwnerNote(first.id))!;
    assert.equal((await node()).review.status, "unreviewed");
    await repo.publish(first.id, 1, true, meta(1));
    const original = (await pool.query("select * from brain_note_versions where note_id=$1", [first.id])).rows;
    const before = (await pool.query("select current_revision,published_revision,public_node,updated_at from brain_notes where id=$1", [first.id])).rows;
    const publicBefore = await repo.findPublicGraph(), review = { result: "confirmed", memo: "PRIVATE_REVIEW_MEMO" }, command = meta(2);
    const duplicate = await Promise.all([repo.reviewNote(first.id, 1, review, command), repo.reviewNote(first.id, 1, review, command)]);
    assert.deepEqual(duplicate[0], duplicate[1]); assert.equal(duplicate[0].commandRevision, 3);
    assert.equal((await node()).review.status, "confirmed");
    assert.equal((await node()).review.history.length, 1);
    assert.deepEqual(await repo.findPublicGraph(), publicBefore);
    assert.deepEqual((await pool.query("select current_revision,published_revision,public_node,updated_at from brain_notes where id=$1", [first.id])).rows, before);
    assert.deepEqual((await repo.listReviewNotes(query())).notes, []);
    assert.equal((await repo.listReviewNotes(query("status=confirmed&reason=questions"))).notes[0].id, first.id);
    assert.doesNotMatch(JSON.stringify((await pool.query("select * from admin_actions")).rows), /PRIVATE_REVIEW/);
    await assert.rejects(repo.reviewNote(first.id, 1, { ...review, memo: "changed" }, command), /command_conflict/);
    await repo.saveDraft(draft, first.id, 1, meta(3));
    assert.equal((await node()).review.status, "needs_review"); assert.equal((await node()).review.checkedAt, null);
    assert((await repo.listReviewNotes(query())).notes[0].reasons.includes("version_changed"));
    assert.deepEqual(await repo.reviewNote(first.id, 1, review, command), duplicate[0]);
    assert.deepEqual(await repo.saveDraft(draft, undefined, 0, save), first);
    await assert.rejects(repo.reviewNote(first.id, 1, review, meta(4)), /revision_conflict/);
    const race = await Promise.allSettled([repo.reviewNote(first.id, 2, review, meta(4)), repo.saveDraft(draft, first.id, 2, meta(4))]);
    assert.equal(race.filter(x => x.status === "fulfilled").length, 1);
    const current = await node(), retry = meta(current.commandRevision);
    await pool.query(`create function reject_review_audit() returns trigger language plpgsql as $$ begin raise exception 'review_audit_failed'; end $$;
      create constraint trigger reject_review_audit after insert on admin_actions deferrable initially deferred for each row execute function reject_review_audit()`);
    await assert.rejects(repo.reviewNote(first.id, current.revision, review, retry), /review_audit_failed/);
    assert.deepEqual(await node(), current);
    assert.equal((await pool.query("select count(*)::int n from admin_actions where command_id=$1", [retry.commandId])).rows[0].n, 0);
    await pool.query("drop trigger reject_review_audit on admin_actions; drop function reject_review_audit()");
    await repo.reviewNote(first.id, current.revision, { result: "needs_review", memo: "근거 재확인" }, retry);
    assert.equal((await node()).review.status, "needs_review");
    assert((await repo.listReviewNotes(query("reason=manual"))).notes.some(n => n.id === first.id));
    await assert.rejects(pool.query("update brain_note_reviews set memo='changed'"), /brain_history_is_immutable/);
    await assert.rejects(pool.query("delete from brain_note_reviews"), /brain_history_is_immutable/);
    assert.deepEqual((await pool.query("select * from brain_note_versions where note_id=$1 and revision=1", [first.id])).rows, original);
    const incoming = await repo.saveDraft({ ...draft, questions: [], links: [{ target: first.id, relation: "supports" as const, reason: "관계" }] }, undefined, 0, meta(0));
    const unlinked = await repo.listReviewNotes(query("status=all&reason=unlinked"));
    assert(!unlinked.notes.some(n => n.id === first.id || n.id === incoming.id));
    for (let i = 0; i < 23; i++) await repo.saveDraft({ ...draft, questions: [], title: `관계 없는 기록 ${i}` }, undefined, 0, meta(0));
    const page1 = await repo.listReviewNotes(query("reason=unlinked")); assert.equal(page1.notes.length, 20); assert(page1.nextCursor);
    const page2 = await repo.listReviewNotes(query("reason=unlinked&after=" + page1.nextCursor)); assert.equal(page2.notes.length, 3); assert.equal(page2.nextCursor, null);
    assert.equal(new Set([...page1.notes, ...page2.notes].map(n => n.id)).size, 23);
    const env = { NODE_ENV: "development", HLOG_ADMIN_ENABLED: "1", HLOG_BRAIN_DATABASE_ENABLED: "1", HLOG_ADMIN_ORIGIN: "http://127.0.0.1:3013", HLOG_ADMIN_OWNER_KEY: "b".repeat(64) };
    const headers = { host: "127.0.0.1:3013", authorization: `Basic ${Buffer.from("owner:" + env.HLOG_ADMIN_OWNER_KEY).toString("base64")}` };
    const response = await handleBrainCaptureRequest(new Request(env.HLOG_ADMIN_ORIGIN + "/admin/brain/records?view=review&reason=unlinked", { headers }), () => repo, env);
    assert.equal(response.status, 200); assert.match(response.headers.get("cache-control")!, /no-store/);
    assert.equal((await response.json()).notes.length, 20);
    const sqlBefore = (await pool.query("select * from brain_note_reviews order by note_id,command_revision")).rows;
    const head = await node();
    for (let i = 0; i < 21; i++) await repo.reviewNote(first.id, head.revision, review, meta(head.commandRevision + i));
    assert.equal((await node()).review.history.length, 20); assert((await node()).review.hasMore);
    assert.equal((await pool.query("select count(*)::int n from brain_note_reviews")).rows[0].n, sqlBefore.length + 21);
    const legacyDraft = { ...draft, questions: undefined, sources: [{ label: "외부 출처", href: "https://example.com/reference" }] };
    delete legacyDraft.questions;
    const legacy = await repo.saveDraft(legacyDraft, undefined, 0, meta(0));
    const legacyQueue = await repo.listReviewNotes(query("status=unreviewed&after=" + legacy.id));
    assert(!legacyQueue.notes.some(n => n.id === legacy.id), "cursor is exclusive");
    const reviewFailure = meta(1);
    await pool.query(`create function reject_review_insert() returns trigger language plpgsql as $$ begin raise exception 'review_insert_failed'; end $$;
      create trigger reject_review_insert before insert on brain_note_reviews for each row execute function reject_review_insert()`);
    await assert.rejects(repo.reviewNote(legacy.id, 1, review, reviewFailure), /review_insert_failed/);
    assert.equal((await repo.getOwnerNote(legacy.id))!.commandRevision, 1);
    assert.equal((await pool.query("select count(*)::int n from admin_actions where command_id=$1", [reviewFailure.commandId])).rows[0].n, 0);
    await pool.query("drop trigger reject_review_insert on brain_note_reviews; drop function reject_review_insert()");
    await repo.reviewNote(legacy.id, 1, review, reviewFailure);
    const checked = (await repo.getOwnerNote(legacy.id))!.review;
    await repo.publish(legacy.id, 1, true, meta(2));
    assert.deepEqual((await repo.getOwnerNote(legacy.id))!.review, checked);
    await repo.unpublish(legacy.id, 1, meta(3));
    assert.deepEqual((await repo.getOwnerNote(legacy.id))!.review, checked);
    const selected = (await repo.listReviewNotes(query("status=confirmed&reason=unlinked"))).notes.find(n => n.id === legacy.id)!;
    assert(selected); assert.deepEqual(selected.reasons, ["unlinked"]);
  } finally { await pool.end(); await admin.query(`drop database ${name}`); await admin.end(); }
});
